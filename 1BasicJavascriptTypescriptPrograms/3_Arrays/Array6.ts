let animals : string[] = ["Goat", "Lion", "Kangroo", "Elephant", "Deer", "Fox", "Moneky"]

//adding an element at the starting index of 0
animals.unshift("Crocodile")
//adding an element at the end index
animals.push("Bear")

//delete an element at starting point
animals.shift()

//delete an element at the end index
animals.pop()

